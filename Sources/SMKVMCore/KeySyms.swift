/// USB HID usage (page 7) → X11 keysym, for standard VNC servers.
///
/// Keys map to their unshifted US-layout symbol; Shift travels as its own
/// key event, which KVM-style VNC servers (iDRAC and similar, which emulate
/// a USB keyboard) turn back into the right scancodes.
public enum KeySyms {
    public static func keysym(forHID hid: UInt8) -> UInt32? {
        switch hid {
        case 0x04...0x1D: return 0x61 + UInt32(hid - 0x04)          // a–z
        case 0x1E...0x26: return 0x31 + UInt32(hid - 0x1E)          // 1–9
        case 0x27: return 0x30                                      // 0
        case 0x3A...0x45: return 0xFFBE + UInt32(hid - 0x3A)        // F1–F12
        case 0x68...0x73: return 0xFFCA + UInt32(hid - 0x68)        // F13–F24
        case 0x59...0x61: return 0xFFB1 + UInt32(hid - 0x59)        // KP 1–9
        default: return table[hid]
        }
    }

    static let table: [UInt8: UInt32] = [
        0x28: 0xFF0D, 0x29: 0xFF1B, 0x2A: 0xFF08, 0x2B: 0xFF09, 0x2C: 0x20,
        0x2D: 0x2D, 0x2E: 0x3D, 0x2F: 0x5B, 0x30: 0x5D, 0x31: 0x5C, 0x32: 0x23,
        0x33: 0x3B, 0x34: 0x27, 0x35: 0x60, 0x36: 0x2C, 0x37: 0x2E, 0x38: 0x2F,
        0x39: 0xFFE5, 0x46: 0xFF61, 0x47: 0xFF14, 0x48: 0xFF13,
        0x49: 0xFF63, 0x4A: 0xFF50, 0x4B: 0xFF55, 0x4C: 0xFFFF, 0x4D: 0xFF57, 0x4E: 0xFF56,
        0x4F: 0xFF53, 0x50: 0xFF51, 0x51: 0xFF54, 0x52: 0xFF52,
        0x53: 0xFF7F, 0x54: 0xFFAF, 0x55: 0xFFAA, 0x56: 0xFFAD, 0x57: 0xFFAB, 0x58: 0xFF8D,
        0x62: 0xFFB0, 0x63: 0xFFAE, 0x64: 0x3C, 0x65: 0xFF67, 0x67: 0xFFBD,
        0xE0: 0xFFE3, 0xE1: 0xFFE1, 0xE2: 0xFFE9, 0xE3: 0xFFEB,
        0xE4: 0xFFE4, 0xE5: 0xFFE2, 0xE6: 0xFFEA, 0xE7: 0xFFEC,
    ]
}
